                    2027 -> listOf("2027-02-06")
                    2028 -> listOf("2028-01-26")
                    2029 -> listOf("2029-02-13")
                    2030 -> listOf("2030-02-03")
                    else -> emptyList()
                }
            }
            "清明节" -> listOf("$year-04-04", "$year-04-05") // 清明节日期在4月4日或5日
            "劳动节" -> listOf("$year-05-01")
            "端午节" -> {
                // 端午节日期需要根据农历计算，这里使用预设数据
                when (year) {
                    2024 -> listOf("2024-06-10")
