                }
            }
            "国庆节" -> listOf("$year-10-01")
            else -> emptyList()
        }
    }

    /**
     * 获取中国传统节日
     *
     * 主数据来自 tyme4j `LunarDay.getFestival()`（依据 GB/T 33661-2017），覆盖：
     * 春节 / 元宵节 / 龙头节 / 上巳节 / 清明节 / 端午节 / 七夕节 / 中元节 /
     * 中秋节 / 重阳节 / 冬至节 / 腊八节 / 除夕。
     *
     * 库未收录「北方小年（腊月廿三）」「南方小年（腊月廿四）」，由本方法补充。
     *
     * @param date 格式为 "yyyy-MM-dd"
     * @return 传统节日名称，如果不是传统节日则返回 null
     */
    fun getTraditionalFestival(date: String): String? {
        val fromLib = runCatching { solarDayOf(date).getLunarDay().getFestival()?.getName() }.getOrNull()
        if (fromLib != null) return fromLib

        // 补充：小年（tyme4j LunarFestival 未收录这两个日期）
        return runCatching {
            val lunar = solarDayOf(date).getLunarDay()
            when {
                lunar.getMonth() == 12 && lunar.getDay() == 23 -> "北方小年"
                lunar.getMonth() == 12 && lunar.getDay() == 24 -> "南方小年"
                else -> null
            }
        }.getOrNull()
    }

    /**
     * tyme4j `SolarFestival` 未收录的公历节日（键为 MM-dd）。
     * 库内置 10 个：元旦 / 妇女节 / 植树节 / 劳动节 / 青年节 / 儿童节 /
     * 建党节 / 建军节 / 教师节 / 国庆节。
     */
    private val extraInternationalFestivals = mapOf(
        "02-14" to "情人节",
        "04-01" to "愚人节",
        "12-25" to "圣诞节"
    )

    /**
     * 获取公历现代节日
     *
     * 主数据来自 tyme4j `SolarDay.getFestival()`，再补充 [extraInternationalFestivals]。
     *
     * @param date 格式为 "yyyy-MM-dd"
     * @return 节日名称，如果不是公历现代节日则返回 null
     */
    fun getInternationalFestival(date: String): String? {
        val fromLib = runCatching { solarDayOf(date).getFestival()?.getName() }.getOrNull()
        if (fromLib != null) return fromLib
        return extraInternationalFestivals[date.takeLast(5)]
    }

    /**
     * 获取日期的完整节日信息（包括节气、传统节日、公历现代节日）
     *
     * 注意：tyme4j 把「清明节」「冬至节」也归入农历传统节日，与节气重名，
     * 此处会跳过，避免同一天重复展示（如「清明」与「清明节」）。
     *
     * @param date 格式为 "yyyy-MM-dd"
     * @return 节日信息列表，可能包含多个节日
     */
    fun getFullFestivalInfo(date: String): List<String> {
        val festivals = mutableListOf<String>()

        // 检查节气
        val solarTerm = getSolarTerm(date)
        if (solarTerm != null) {
            festivals.add(solarTerm)
        }

        // 检查传统节日
        val traditionalFestival = getTraditionalFestival(date)
        if (traditionalFestival != null && traditionalFestival != "${solarTerm}节") {
            festivals.add(traditionalFestival)
        }

        // 检查公历现代节日
        val internationalFestival = getInternationalFestival(date)
        if (internationalFestival != null) {
            festivals.add(internationalFestival)
        }

        // 去重（例如端午节既是传统节日又是法定节假日）
        return festivals.distinct()
    }
