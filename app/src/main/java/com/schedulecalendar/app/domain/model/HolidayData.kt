    /**
     * 法定节假日名称映射（用于倒计时显示）
     * key: 节假日名称
     * value: 该节假日的代表日期（用于计算倒计时）
     */
    private val statutoryHolidayNames = listOf(
        "元旦", "春节", "清明节", "劳动节", "端午节", "中秋节", "国庆节"
    )

    /**
     * 计算距离下一个法定节假日的天数
     * @param currentDate 当前日期，格式为 "yyyy-MM-dd"
     * @return Pair<节假日名称, 剩余天数>，如果当天是节假日则天数为0
     */
    fun getNextHolidayCountdown(currentDate: String): Pair<String, Int> {
        val parts = currentDate.split("-")
        val year = parts[0].toInt()
        val month = parts[1].toInt()
        val day = parts[2].toInt()
        val current = java.time.LocalDate.of(year, month, day)

        // 检查当天是否为节假日
        val todayHoliday = getHolidayName(currentDate)
        if (todayHoliday != null && todayHoliday !in listOf("春节补班", "劳动节补班", "端午节补班", "中秋节补班", "国庆节补班")) {
            return Pair(todayHoliday, 0)
        }

        // 查找下一个节假日
        var nextHoliday: String? = null
        var nextHolidayDate: java.time.LocalDate? = null
        var minDays = Int.MAX_VALUE

        // 遍历所有法定节假日，找最近的
        for (holidayName in statutoryHolidayNames) {
            // 获取该节假日在当前年份和下一年份的日期
            val holidayDates = getHolidayDatesForYear(holidayName, year)
            val holidayDatesNextYear = getHolidayDatesForYear(holidayName, year + 1)

            // 检查当前年份的节假日
            for (dateStr in holidayDates) {
                val dateParts = dateStr.split("-")
                val holidayDate = java.time.LocalDate.of(
                    dateParts[0].toInt(), dateParts[1].toInt(), dateParts[2].toInt()
                )
                val daysBetween = java.time.temporal.ChronoUnit.DAYS.between(current, holidayDate).toInt()
                if (daysBetween > 0 && daysBetween < minDays) {
                    minDays = daysBetween
                    nextHoliday = holidayName
                    nextHolidayDate = holidayDate
                }
            }

            // 检查下一年份的节假日
            for (dateStr in holidayDatesNextYear) {
                val dateParts = dateStr.split("-")
                val holidayDate = java.time.LocalDate.of(
                    dateParts[0].toInt(), dateParts[1].toInt(), dateParts[2].toInt()
                )
                val daysBetween = java.time.temporal.ChronoUnit.DAYS.between(current, holidayDate).toInt()
                if (daysBetween > 0 && daysBetween < minDays) {
                    minDays = daysBetween
                    nextHoliday = holidayName
                    nextHolidayDate = holidayDate
                }
            }
        }

        return if (nextHoliday != null) {
            Pair(nextHoliday, minDays)
        } else {
            Pair("未知", -1)
        }
    }

    /**
     * 获取指定年份某个法定节假日的代表日期列表
     * @param holidayName 节假日名称
     * @param year 年份
     * @return 该节假日的日期列表（取第一天作为代表）
     */
    private fun getHolidayDatesForYear(holidayName: String, year: Int): List<String> {
        return when (holidayName) {
            "元旦" -> listOf("$year-01-01")
            "春节" -> {
                // 春节日期需要根据农历计算，这里使用预设数据
                when (year) {
                    2024 -> listOf("2024-02-10")
                    2025 -> listOf("2025-01-29")
                    2026 -> listOf("2026-02-17")
                    2027 -> listOf("2027-02-06")
                    2028 -> listOf("2028-01-26")
                    2029 -> listOf("2029-02-13")
                    2030 -> listOf("2030-02-03")
                    else -> emptyList()
                }
            }
            "清明节" -> listOf("$year-04-04", "$year-04-05") // 清明节日期在4月4日或5日
            "劳动节" -> listOf("$year-05-01")
            "端午节" -> {
                // 端午节日期需要根据农历计算，这里使用预设数据
                when (year) {
                    2024 -> listOf("2024-06-10")
                    2025 -> listOf("2025-05-31")
                    2026 -> listOf("2026-06-19")
                    2027 -> listOf("2027-06-09")
                    2028 -> listOf("2028-05-28")
                    2029 -> listOf("2029-06-07")
                    2030 -> listOf("2030-06-06")
                    else -> emptyList()
                }
            }
            "中秋节" -> {
                // 中秋节日期需要根据农历计算，这里使用预设数据
                when (year) {
                    2024 -> listOf("2024-09-15")
                    2025 -> listOf("2025-10-06")
                    2026 -> listOf("2026-09-25")
                    2027 -> listOf("2027-09-15")
                    2028 -> listOf("2028-10-03")
                    2029 -> listOf("2029-09-06")
                    2030 -> listOf("2030-09-20")
                    else -> emptyList()
                }
            }
            "国庆节" -> listOf("$year-10-01")
            else -> emptyList()
        }
    }

    /**
     * 获取中国传统节日（非法定节假日）
     * @param date 格式为 "yyyy-MM-dd"
     * @return 传统节日名称，如果不是传统节日则返回 null
     */
    fun getTraditionalFestival(date: String): String? {
        val parts = date.split("-")
        val year = parts[0].toInt()
        val month = parts[1].toInt()
        val day = parts[2].toInt()

        // 使用农历计算传统节日
        val lunar = LunarCalendar.solarToLunar(year, month, day)
        val lunarMonth = lunar.lunarMonth
        val lunarDay = lunar.lunarDay

        return when {
            lunarMonth == 1 && lunarDay == 1 -> "春节"
            lunarMonth == 1 && lunarDay == 15 -> "元宵节"
            lunarMonth == 2 && lunarDay == 2 -> "龙抬头"
            lunarMonth == 3 && lunarDay == 3 -> "上巳节"
            lunarMonth == 5 && lunarDay == 5 -> "端午节"
            lunarMonth == 7 && lunarDay == 7 -> "七夕节"
            lunarMonth == 7 && lunarDay == 15 -> "中元节"
            lunarMonth == 8 && lunarDay == 15 -> "中秋节"
            lunarMonth == 9 && lunarDay == 9 -> "重阳节"
            lunarMonth == 12 && lunarDay == 8 -> "腊八节"
            lunarMonth == 12 && lunarDay == 23 -> "北方小年"
            lunarMonth == 12 && lunarDay == 24 -> "南方小年"
            lunarMonth == 12 && lunarDay == 30 -> "除夕"
            // 处理腊月二十九为除夕的情况（小月）
            lunarMonth == 12 && lunarDay == 29 && !lunar.isLeap -> {
                // 检查是否是腊月最后一天
                val nextDay = java.time.LocalDate.of(year, month, day).plusDays(1)
                val nextLunar = LunarCalendar.solarToLunar(nextDay.year, nextDay.monthValue, nextDay.dayOfMonth)
                if (nextLunar.lunarMonth == 1 && nextLunar.lunarDay == 1) "除夕" else null
            }
            else -> null
        }
    }

    /**
     * 获取国际节日
     * @param date 格式为 "yyyy-MM-dd"
     * @return 国际节日名称，如果不是国际节日则返回 null
     */
    fun getInternationalFestival(date: String): String? {
        val parts = date.split("-")
        val month = parts[1].toInt()
        val day = parts[2].toInt()

        return when {
            month == 1 && day == 1 -> "元旦"
            month == 2 && day == 14 -> "情人节"
            month == 3 && day == 8 -> "妇女节"
            month == 3 && day == 12 -> "植树节"
            month == 4 && day == 1 -> "愚人节"
            month == 5 && day == 1 -> "劳动节"
            month == 5 && day == 4 -> "青年节"
            month == 6 && day == 1 -> "儿童节"
            month == 7 && day == 1 -> "建党节"
            month == 8 && day == 1 -> "建军节"
            month == 9 && day == 10 -> "教师节"
            month == 10 && day == 1 -> "国庆节"
            month == 12 && day == 25 -> "圣诞节"
            else -> null
        }
    }

    /**
     * 获取日期的完整节日信息（包括节气、传统节日、国际节日）
     * @param date 格式为 "yyyy-MM-dd"
     * @return 节日信息列表，可能包含多个节日
     */
    fun getFullFestivalInfo(date: String): List<String> {
        val festivals = mutableListOf<String>()

        // 检查节气
        val solarTerm = getSolarTerm(date)
        if (solarTerm != null) {
            festivals.add(solarTerm)
        }

        // 检查传统节日
        val traditionalFestival = getTraditionalFestival(date)
        if (traditionalFestival != null) {
            festivals.add(traditionalFestival)
        }

        // 检查国际节日
        val internationalFestival = getInternationalFestival(date)
        if (internationalFestival != null) {
            festivals.add(internationalFestival)
        }

        // 去重（例如端午节既是传统节日又是法定节假日）
        return festivals.distinct()
    }
