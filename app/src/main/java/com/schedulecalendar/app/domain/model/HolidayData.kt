    // 二十四节气（tyme4j 天文算法，任意年份）
    // ════════════════════════════════════════════════════════════════════════════

    /**
     * 获取指定日期的节气名称
     *
     * 由 tyme4j `SolarDay.getTermDay()` 的「寿星天文历」算法实时推算，
     * 取代原先 2024–2030 的硬编码表（原表见 git 历史）。收益：
     * 1. 任意年份均正确，消除「2030 年之后无法识别节气」的隐患；
     * 2. 无需每年手工维护节气日期。
     *
     * @param date 格式为 "yyyy-MM-dd"
     * @return 节气名称，如果该日不是节气则返回 null
     */
    fun getSolarTerm(date: String): String? = runCatching {
        val termDay = solarDayOf(date).getTermDay()
        if (termDay.getDayIndex() == 0) termDay.getSolarTerm().getName() else null
    }.getOrNull()

    /** 解析 "yyyy-MM-dd" 为 tyme4j 公历日；格式非法时抛异常，由调用方 runCatching 兜底 */
    private fun solarDayOf(date: String): SolarDay = SolarDay.fromYmd(
        date.substring(0, 4).toInt(),
        date.substring(5, 7).toInt(),
        date.substring(8, 10).toInt()
    )

    /**
     * 法定节假日名称映射（用于倒计时显示）
     * key: 节假日名称
     * value: 该节假日的代表日期（用于计算倒计时）
     */
    private val statutoryHolidayNames = listOf(
        "元旦", "春节", "清明节", "劳动节", "端午节", "中秋节", "国庆节"
    )

    /**
     * 计算距离下一个法定节假日的天数
     * @param currentDate 当前日期，格式为 "yyyy-MM-dd"
     * @return Pair<节假日名称, 剩余天数>，如果当天是节假日则天数为0
     */
    fun getNextHolidayCountdown(currentDate: String): Pair<String, Int> {
        val parts = currentDate.split("-")
        val year = parts[0].toInt()
        val month = parts[1].toInt()
        val day = parts[2].toInt()
        val current = java.time.LocalDate.of(year, month, day)

        // 检查当天是否为节假日（调休补班日不算「在放假」）
        val todayHoliday = getHolidayName(currentDate)
        if (todayHoliday != null && !isMakeupDay(currentDate)) {
            return Pair(todayHoliday, 0)
        }

        // 查找下一个节假日
        var nextHoliday: String? = null
        var nextHolidayDate: java.time.LocalDate? = null
        var minDays = Int.MAX_VALUE

        // 遍历所有法定节假日，找最近的
        for (holidayName in statutoryHolidayNames) {
            // 获取该节假日在当前年份和下一年份的日期
            val holidayDates = getHolidayDatesForYear(holidayName, year)
            val holidayDatesNextYear = getHolidayDatesForYear(holidayName, year + 1)

            // 检查当前年份的节假日
            for (dateStr in holidayDates) {
                val dateParts = dateStr.split("-")
                val holidayDate = java.time.LocalDate.of(
                    dateParts[0].toInt(), dateParts[1].toInt(), dateParts[2].toInt()
                )
                val daysBetween = java.time.temporal.ChronoUnit.DAYS.between(current, holidayDate).toInt()
                if (daysBetween > 0 && daysBetween < minDays) {
                    minDays = daysBetween
                    nextHoliday = holidayName
                    nextHolidayDate = holidayDate
                }
            }

            // 检查下一年份的节假日
            for (dateStr in holidayDatesNextYear) {
                val dateParts = dateStr.split("-")
                val holidayDate = java.time.LocalDate.of(
                    dateParts[0].toInt(), dateParts[1].toInt(), dateParts[2].toInt()
                )
                val daysBetween = java.time.temporal.ChronoUnit.DAYS.between(current, holidayDate).toInt()
                if (daysBetween > 0 && daysBetween < minDays) {
                    minDays = daysBetween
                    nextHoliday = holidayName
                    nextHolidayDate = holidayDate
                }
            }
        }

        return if (nextHoliday != null) {
            Pair(nextHoliday, minDays)
        } else {
            Pair("未知", -1)
        }
    }

    /**
     * 获取指定年份某个法定节假日的代表日期列表
     * @param holidayName 节假日名称
     * @param year 年份
     * @return 该节假日的日期列表（取第一天作为代表）
     */
    private fun getHolidayDatesForYear(holidayName: String, year: Int): List<String> {
        return when (holidayName) {
            "元旦" -> listOf("$year-01-01")
            "春节" -> {
